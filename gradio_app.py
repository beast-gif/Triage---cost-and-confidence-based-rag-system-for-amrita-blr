"""
gradio_app.py — chat interface for Triage, mounted on the existing FastAPI app.

    Gradio UI  ->  /
    JSON API   ->  /chat, /score, /health, /sync/*
    Swagger    ->  /docs

Both surfaces share one process, so the models load once and serve both.

WHY THE CONFIDENCE BADGE IS PART OF THE UI
------------------------------------------
The contribution of this project is not that it answers questions — every RAG
bot does that. It is that it knows when it CANNOT answer, and skips the
generation call entirely when retrieval failed. If the interface hides that,
the demo looks like any other chatbot.

So every answer carries its band, the retrieval route that produced it, and
whether the LLM was called at all. A refusal reads:

    LOW 0.08 · plain search · LLM skipped — no cost incurred

which is the whole thesis in one line.

Run locally:
    python gradio_app.py
"""

import asyncio

import gradio as gr

