BAND_STYLE = {
    "high": ("#1a7f37", "HIGH"),
    "medium": ("#9a6700", "MEDIUM"),
    "low": ("#b42318", "LOW"),
}

EMPTY_DB_NOTICE = """
### Database is empty

Triage has no data to search yet. Open the **Data** tab and run a sync — it
scrapes the Amrita Bengaluru admissions pages and builds the vector store.

This takes roughly 10–15 minutes: 26 seed pages in pass 1, then a few hundred
faculty profile pages discovered from the faculty card grids in pass 2.
"""


def _badge(result):
    """One line summarising how the answer was produced."""
    band = result.get("band", "low")
    colour, label = BAND_STYLE.get(band, BAND_STYLE["low"])
    confidence = result.get("confidence") or 0.0
    route = result.get("route") or "plain search"

    if not result.get("llm_called"):
        cost = "LLM skipped — no cost incurred"
    else:
        model = (result.get("model") or "").split("/")[-1]
        cost = f"generated by {model}" if model else "LLM called"

    return (
        f"<div style='font-size:0.85em;color:#666;margin-top:8px'>"
        f"<span style='color:{colour};font-weight:600'>{label} {confidence}</span>"
        f" &nbsp;·&nbsp; {route} &nbsp;·&nbsp; {cost}</div>"
    )


def _sources(result):
    urls = result.get("sources") or []
    if not urls:
        return ""
    lines = "\n".join(f"- [{u.split('//')[-1][:70]}]({u})" for u in urls)
    return f"\n\n**Sources**\n{lines}"


def respond(message, history):
    """Gradio chat callback. Returns the updated history."""
    from store import count

    if count() == 0:
        history.append({"role": "user", "content": message})
        history.append({"role": "assistant", "content": EMPTY_DB_NOTICE})
        return history, ""

    from generator import answer_query

    try:
        result = asyncio.run(answer_query(message))
    except Exception as exc:
        history.append({"role": "user", "content": message})
        history.append({"role": "assistant",
                        "content": f"Something went wrong: `{exc}`"})
        return history, ""

    reply = result["answer"] + _sources(result) + _badge(result)
    history.append({"role": "user", "content": message})
    history.append({"role": "assistant", "content": reply})
    return history, ""


def inspect(message):
    """Retrieval + confidence only. No LLM call, so this is free to run."""
    from confidence import score_query
    from store import count

    if not message.strip():
        return "Type a question first."
    if count() == 0:
        return EMPTY_DB_NOTICE

    result = asyncio.run(score_query(message))
    d = result.get("retrieval_details", {})

    lines = [
        f"**{result['band'].upper()} {result['final_confidence']}** &nbsp;·&nbsp; "
        f"route: `{result.get('route') or 'plain search'}` &nbsp;·&nbsp; "
        f"mode: `{result['generator_mode']}`",
        "",
        f"- `abs_signal` **{d.get('abs_signal')}** — is the top chunk strong on its own?",
    ]
    if d.get("filtered_pool"):
        lines.append("- `sep_signal` **n/a** — filtered pool, no rejected set to measure")
        lines.append(f"- `set_confidence` **{d.get('set_confidence')}** = max(abs, rank)")
    else:
        lines.append(f"- `sep_signal` **{d.get('sep_signal')}** — does it tower over this query's noise floor?")
        lines.append(f"- `set_confidence` **{d.get('set_confidence')}** = max(abs, sep)")
    lines.append(f"- `rank_confidence` **{d.get('rank_confidence')}** — do we know *which* chunk?")
    lines.append(f"- `agreement` **{d.get('ensemble_agreement')}** — 5-model category vote")
    lines.append("\n**Retrieved chunks**\n")

    for i, c in enumerate(result.get("chunks", []), start=1):
        preview = " ".join(c["content"].split())[:180]
        lines.append(f"{i}. `{c['rerank_score']:.4f}` — {c['source_url']}  \n   {preview}…")

    return "\n".join(lines)


def data_status():
    from scheduler import STATUS, next_run_time
    from store import count

    total = count()
    rows = [f"**Chunks in vector store:** {total or 0}"]

    if total == 0:
        rows.append("\nThe database is empty. Run a sync to populate it.")
    if STATUS["last_run"]:
        rows.append(f"\n**Last sync:** {STATUS['last_run']} "
                    f"({STATUS['last_status']}, {STATUS['last_duration_seconds']}s)")
    if STATUS["last_error"]:
        rows.append(f"\n**Last error:** `{STATUS['last_error']}`")

    scheduler = getattr(fastapi_app.state, "scheduler", None)
    upcoming = next_run_time(scheduler)
    if upcoming:
        rows.append(f"\n**Next scheduled sync:** {upcoming}")

    health = STATUS.get("health")
    if health:
        rows.append(f"\n**Departments with their own head:** "
                    f"{health['departments_with_heads'] or 'none'}")
        for warning in health["warnings"]:
            rows.append(f"\n⚠️ {warning}")

    return "\n".join(rows)


def trigger_sync():
    """Blocking on purpose — the user asked for it and wants to see the result."""
    from scheduler import run_sync

    result = run_sync(triggered_by="gradio")
    if result["status"] == "busy":
        return "A sync is already running. Check back in a few minutes."
    if result["status"] == "failed":
        return (f"Sync failed: `{result['detail']}`\n\n"
                f"If this mentions Playwright or a browser, Crawl4AI could not "
                f"launch a headless browser in this container.")
    return f"Sync complete — {result['chunks']} chunks in the vector store.\n\n" \
           + data_status()


